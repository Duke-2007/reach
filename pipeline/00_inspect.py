"""
00_inspect.py - metadata-only inspection of the raw EICV7 files.

Prints and saves to docs/data-notes.md, for every file in data/raw:
  - file name, rows, columns
  - every column: name, dtype, variable label, missing share
  - value labels (coding of categories) when the file has them
  - unique hhid / pid counts and whether the file is household- or person-level

It never prints or saves any data row, only metadata. The output is safe to
share with an AI assistant.

Very large files (> BIG_MB) are read in metadata-only mode (names, labels and
row count, but no missing shares) so the script cannot run out of memory.

Run from the repo root:   python pipeline/00_inspect.py
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
OUT = ROOT / "docs" / "data-notes.md"
SUPPORTED = {".dta", ".sav", ".csv"}
MAX_VALUE_LABELS = 12   # keep the notes readable
BIG_MB = 150            # files larger than this are read metadata-only


def load(path: Path):
    """Return (dataframe, column labels, value labels, n_rows, metadata_only)."""
    ext = path.suffix.lower()
    big = path.stat().st_size > BIG_MB * 1024 * 1024
    if ext in (".dta", ".sav"):
        import pyreadstat
        reader = pyreadstat.read_dta if ext == ".dta" else pyreadstat.read_sav
        # Some NISR files were saved with a legacy Windows encoding instead of
        # UTF-8, so retry with common fallbacks if the default fails.
        last_err = None
        for enc in (None, "latin1", "cp1252"):
            try:
                df, meta = reader(str(path), metadataonly=big, encoding=enc)
                break
            except UnicodeDecodeError as exc:
                last_err = exc
        else:
            raise last_err
        n_rows = meta.number_rows if big else len(df)
        return (df, dict(meta.column_names_to_labels),
                dict(meta.variable_value_labels), n_rows, big)
    if big:
        df = pd.read_csv(path, nrows=1000)
        return df, {}, {}, -1, True
    df = pd.read_csv(path, low_memory=False)
    return df, {}, {}, len(df), False


def find_col(df, names):
    lower = {c.lower(): c for c in df.columns}
    for n in names:
        if n in lower:
            return lower[n]
    return None


def inspect(path: Path, lines: list):
    df, labels, value_labels, n_rows, meta_only = load(path)
    hh = find_col(df, ["hhid", "hh_id", "hhold", "household_id"])
    pid = find_col(df, ["pid", "person_id", "indid"])

    lines.append(f"\n## {path.name}\n")
    lines.append(f"- size: {path.stat().st_size / 1024 / 1024:.1f} MB")
    lines.append(f"- rows: {n_rows:,}   columns: {df.shape[1]}")
    if meta_only:
        lines.append("- large file: metadata only (no missing shares, no id counts)")
    elif hh:
        n_hh = df[hh].nunique(dropna=True)
        lines.append(f"- household id column: `{hh}`, unique values: {n_hh:,}")
        if pid:
            lines.append(f"- person id column: `{pid}` -> PERSON-level file "
                         f"({len(df) / max(n_hh, 1):.1f} rows per household)")
        elif n_hh == len(df):
            lines.append("- one row per household -> HOUSEHOLD-level file")
        else:
            lines.append(f"- {len(df) / max(n_hh, 1):.1f} rows per household "
                         "(repeated rows: check what the extra rows are)")
    else:
        lines.append("- no obvious household id column found (check names below)")

    lines.append("\n| column | dtype | label | missing % |")
    lines.append("|---|---|---|---|")
    for c in df.columns:
        miss = "n/a" if meta_only else f"{df[c].isna().mean() * 100:.1f}"
        label = str(labels.get(c, "") or "").replace("|", "/")
        lines.append(f"| {c} | {df[c].dtype} | {label} | {miss} |")

    coded = {c: v for c, v in value_labels.items() if v}
    if coded:
        lines.append("\nValue labels (coding):")
        for c, mapping in coded.items():
            items = list(mapping.items())[:MAX_VALUE_LABELS]
            text = "; ".join(f"{k}={v}" for k, v in items)
            more = " ..." if len(mapping) > MAX_VALUE_LABELS else ""
            lines.append(f"- `{c}`: {text}{more}")


def main():
    files = sorted(p for p in RAW.rglob("*") if p.suffix.lower() in SUPPORTED)
    if not files:
        raise SystemExit(f"No .dta/.sav/.csv files found in {RAW}")
    lines = ["# Data notes (generated by pipeline/00_inspect.py)",
             "", "Metadata only: no data rows are stored in this file.",
             "", f"Files found: {len(files)}"]
    for p in files:
        print(f"Inspecting {p.name} ...")
        try:
            inspect(p, lines)
        except Exception as exc:  # keep going, report the problem
            lines.append(f"\n## {p.name}\n\nCOULD NOT READ: {exc}")
            print(f"  failed: {exc}")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nSaved {OUT}")


if __name__ == "__main__":
    main()
